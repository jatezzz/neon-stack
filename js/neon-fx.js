/*
    Neon FX: the celebrations shared by every Neon game (one universe): win, best (new record of the day), lose.

    The same three Lottie files (fx/win.json, fx/best.json, fx/lose.json) and the same player (js/vendor/
    lottie_light.min.js, lottie-web 5.12.2, MIT) ship with Neon Raiders, Neon Bricks, Neon Stack and Neon Command.
    Generated by make_fx.py; do not edit the JSON by hand.

        NeonFx.preload()                      // at the start of a run: fetch the player and the files quietly
        NeonFx.celebrate(kind, onCard)        // kind: 'win' | 'best' | 'lose'; on the game-over card or over the game
        NeonFx.portalDelay()                  // ms a portal should wait before covering the game (0 if nothing plays)

    The player is loaded only when needed and never blocks the game: if anything fails, nothing is shown.
    People who ask their system for less motion see the last frame, still.
*/
(function () {
    'use strict';

    var script = document.currentScript;
    var BASE = script && script.src ? script.src.replace(/js\/neon-fx\.js.*$/, '') : '';
    var KINDS = ['win', 'best', 'lose'];
    var lib = null, files = {}, playing = 0;

    function calm() { return window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches; }

    function player() {
        if (window.lottie) { return Promise.resolve(window.lottie); }
        if (!lib) {
            lib = new Promise(function (resolve, reject) {
                var s = document.createElement('script');
                s.src = BASE + 'js/vendor/lottie_light.min.js?v=5.12.2';
                s.onload = function () { resolve(window.lottie); };
                s.onerror = reject;
                document.head.appendChild(s);
            });
        }
        return lib;
    }

    function file(kind) {
        if (!files[kind]) {
            files[kind] = fetch(BASE + 'fx/' + kind + '.json?v=1').then(function (r) { return r.json(); });
        }
        return files[kind];
    }

    function preload() {
        try { player().catch(function () {}); KINDS.forEach(function (k) { file(k).catch(function () {}); }); } catch (err) { /* never break the game */ }
    }

    //  On the card: a box at its top that keeps the last frame. Over the game: centred, then it fades away.
    function host(onCard) {
        if (onCard) {
            var box = document.getElementById('goFx');
            if (box) { box.innerHTML = ''; box.hidden = false; }
            return box;
        }
        var stage = document.getElementById('stage');
        if (!stage) { return null; }
        var layer = document.createElement('div');
        layer.className = 'nfx-stage';
        stage.appendChild(layer);
        return layer;
    }

    function celebrate(kind, onCard) {
        if (KINDS.indexOf(kind) < 0) { return; }
        if (window.NeonStage) { window.NeonStage.stinger(kind); }          // the universe's ending jingle (neon-stage.js)
        var box = host(onCard);
        if (!box) { return; }
        playing = Date.now();
        Promise.all([player(), file(kind)]).then(function (r) {
            var anim = r[0].loadAnimation({ container: box, renderer: 'svg', loop: false, autoplay: !calm(), animationData: r[1] });
            if (calm()) { anim.goToAndStop(r[1].op - 1, true); }
            if (!onCard) {
                setTimeout(function () { box.style.opacity = '0'; }, 1500);
                setTimeout(function () { anim.destroy(); if (box.parentNode) { box.parentNode.removeChild(box); } }, 2100);
            }
        }).catch(function () { if (!onCard && box.parentNode) { box.parentNode.removeChild(box); } });
    }

    //  A portal that shows its own result screen should wait for the celebration over the game.
    function portalDelay() { return Date.now() - playing < 300 ? 1700 : 0; }

    //  The styles, injected once so every game gets the same look.
    var css = '.nfx-stage{position:absolute;left:0;top:0;right:0;bottom:0;display:flex;align-items:center;justify-content:center;' +
              'pointer-events:none;z-index:15;transition:opacity .5s}.nfx-stage>svg{width:62%!important;height:auto!important}' +
              '#goFx{width:120px;height:120px;margin:-6px auto 2px}#goFx[hidden]{display:none}';
    try { var st = document.createElement('style'); st.textContent = css; document.head.appendChild(st); } catch (err) { /* no DOM */ }

    window.NeonFx = { preload: preload, celebrate: celebrate, portalDelay: portalDelay, kinds: KINDS };
})();
